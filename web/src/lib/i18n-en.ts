/** Pola waktu relatif, tanggal, dan satuan yang sering muncul di dalam teks. */
export function enPhrases(t: string): string {
  return t
    .replace(/\b(\d+) (?:jam|j) lalu\b/g, (_m, n: string) => `${n}h ago`)
    .replace(/\b(\d+) (?:menit|mnt) lalu\b/g, (_m, n: string) => `${n}m ago`)
    .replace(/\b(\d+) hari lalu\b/g, (_m, n: string) => `${n}d ago`)
    .replace(/\b(\d+) minggu lalu\b/g, (_m, n: string) => `${n}w ago`)
    .replace(/\bbaru saja\b/g, "just now")
    .replace(/\b(\d+) (?:menit|mnt) baca\b/g, (_m, n: string) => `${n} min read`)
    .replace(/\b(\d+) (?:detik) baca\b/g, (_m, n: string) => `${n} sec read`)
    .replace(/\b(\d{1,2}) (Jan|Feb|Mar|Apr|Mei|Jun|Jul|Agu|Agt|Sep|Okt|Nov|Des)\b/g, (_m, d: string, mo: string) => `${d} ${MONTHS[mo]}`)
    .replace(/\b(Januari|Februari|Maret|April|Mei|Juni|Juli|Agustus|September|Oktober|November|Desember)\b/g, (m) => MONTHS_LONG[m] ?? m)
    .replace(/\b(Senin|Selasa|Rabu|Kamis|Jumat|Sabtu|Minggu)\b/g, (m) => DAYS[m] ?? m)
    .replace(/^(Saham|Komoditas|Ekonomi|Analisis|Kebijakan|Emiten|Crypto|Forex|Makro|Valas)( · )/, (_m, c: string, sep: string) => `${CAT[c] ?? c}${sep}`)
    .replace(/(\d)\s?rb\b/g, "$1K")
    .replace(/(\d)\s?jt\b/g, "$1M")
    .replace(/\bSetiap hari\b/g, "Every day")
    .replace(/\bperangkat aktif\b/g, "active devices")
    .replace(/\baset dipantau\b/g, "assets tracked")
    .replace(/\balert harga aktif\b/g, "active price alerts")
    .replace(/\bterpicu\b/g, "triggered")
    .replace(/\bpengikut\b/g, "followers")
    .replace(/\bartikel\b/g, "articles")
    .replace(/\bKemarin\b/g, "Yesterday");
}
